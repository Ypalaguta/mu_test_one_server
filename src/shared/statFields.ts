export type StatName = typeof statFields[number];
export type Stats = Record<StatName, number>;

// Existing Mongo documents can still use the earlier names. Explicit new values take precedence, including zero.
const legacyNames: Partial<Record<StatName, string>> = {
  spellDamageInc: 'spellDamage',
  attackDamageInc: 'meleeDamage',
  physicalDamageInc: 'meleeAttackInc',
  attackPhysicalFlat: 'meleeAttackFlat',
  attackPenetration: 'meleePenetration',
  attackSpeed: 'meleeAttackSpeed',
  attackSpeedInc: 'meleeAttackSpeedInc',
  attackAccuracyInc: 'meleeAccuracyInc',
  attackFireFlat: 'meleeFireFlat',
  attackFireInc: 'meleeFireInc',
  attackColdFlat: 'meleeColdFlat',
  attackColdInc: 'meleeColdInc',
  attackLightningFlat: 'meleeLightningFlat',
  attackLightningInc: 'meleeLightningInc',
  attackChaosFlat: 'meleeChaosFlat',
  attackChaosInc: 'meleeChaosInc',
  attackElementalInc: 'meleeElementalInc',
};
export function readStats(value: Partial<Record<string, number>> | null | undefined): Stats {
  return Object.fromEntries(statFields.map(name => [name, value?.[name] ?? value?.[legacyNames[name] ?? name] ?? 0])) as Stats;
}
